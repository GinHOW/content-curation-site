import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(scriptDirectory, '..')
const screenDirectory = path.join(projectRoot, 'source-assets/spatial-controller/screens')
const outputFile = path.join(projectRoot, 'src/data/spatial/controllerScreenZones.js')

// screen-main.svg and the individual screen SVGs share the same Illustrator
// coordinate system, but their exported artboard is translated. Calibrate that
// source system against the controller's central transparent screen in percent.
const targetMain = {
  left: 31.68,
  top: 19.5,
  width: 36.37,
  height: 29.95,
}

// Keep a small overscan around each aperture so a transformed image/static layer
// cannot reveal a white seam at the physical screen frame.
const contentOverscan = {
  x: 0.18,
  y: 0.3,
}

// Expand only the transformed content target by this many stage percentage
// points. The clip stays faithful to the SVG; this covers anti-aliased edges.
const perspectiveBleed = 0.14

function readSvg(name) {
  return fs.readFileSync(path.join(screenDirectory, name), 'utf8')
}

function readAttribute(tag, name) {
  const match = tag.match(new RegExp(`${name}="([^"]+)"`))
  return match ? match[1] : null
}

function readScreenShape(svg, id) {
  const tagPattern = new RegExp(
    `<(?:polygon|polyline|rect)[^>]*id="${id}(?:_[^"]+)?"[^>]*\\/?\\s*>`,
    's',
  )
  const tag = svg.match(tagPattern)?.[0]
  if (!tag) throw new Error(`Missing ${id} shape`)

  if (tag.startsWith('<rect')) {
    const x = Number(readAttribute(tag, 'x'))
    const y = Number(readAttribute(tag, 'y'))
    const width = Number(readAttribute(tag, 'width'))
    const height = Number(readAttribute(tag, 'height'))
    return [
      { x, y },
      { x, y: y + height },
      { x: x + width, y: y + height },
      { x: x + width, y },
    ]
  }

  const points = readAttribute(tag, 'points')
  if (!points) throw new Error(`Missing points for ${id}`)
  return points
    .trim()
    .split(/\s+/)
    .map((point) => {
      const [x, y] = point.split(',').map(Number)
      return { x, y }
    })
}

function readMainShape() {
  const source = readScreenShape(readSvg('screen-main.svg'), 'screen-main')
  const xs = source.map((point) => point.x)
  const ys = source.map((point) => point.y)
  return {
    left: Math.min(...xs),
    top: Math.min(...ys),
    width: Math.max(...xs) - Math.min(...xs),
    height: Math.max(...ys) - Math.min(...ys),
  }
}

function calibrate(sourceMain) {
  return {
    scaleX: targetMain.width / sourceMain.width,
    scaleY: targetMain.height / sourceMain.height,
    offsetX: targetMain.left - (targetMain.width / sourceMain.width) * sourceMain.left,
    offsetY: targetMain.top - (targetMain.height / sourceMain.height) * sourceMain.top,
  }
}

function toPercent(point, calibration) {
  return {
    x: point.x * calibration.scaleX + calibration.offsetX,
    y: point.y * calibration.scaleY + calibration.offsetY,
  }
}

function orderQuad(points) {
  if (points.length !== 4) throw new Error('Every screen must have four corners')
  const byY = [...points].sort((a, b) => a.y - b.y)
  const top = byY.slice(0, 2).sort((a, b) => a.x - b.x)
  const bottom = byY.slice(2).sort((a, b) => a.x - b.x)
  return [top[0], bottom[0], bottom[1], top[1]]
}

function round(value) {
  return Number(value.toFixed(3))
}

function formatClip(quad) {
  return `polygon(${quad.map((point) => `${round(point.x)}% ${round(point.y)}%`).join(', ')})`
}

function formatContent(quad) {
  const xs = quad.map((point) => point.x)
  const ys = quad.map((point) => point.y)
  const left = Math.min(...xs) - contentOverscan.x
  const top = Math.min(...ys) - contentOverscan.y
  const right = Math.max(...xs) + contentOverscan.x
  const bottom = Math.max(...ys) + contentOverscan.y
  return {
    top: `${round(top)}%`,
    left: `${round(left)}%`,
    width: `${round(right - left)}%`,
    height: `${round(bottom - top)}%`,
  }
}

const calibration = calibrate(readMainShape())
const zones = Array.from({ length: 18 }, (_, index) => {
  const id = `screen${index + 1}`
  const points = readScreenShape(readSvg(`${id}.svg`), id).map((point) =>
    toPercent(point, calibration),
  )
  const quad = orderQuad(points)
  return {
    id,
    clip: formatClip(quad),
    content: formatContent(quad),
  }
})

const output = `// Generated by scripts/generate-controller-screen-zones.mjs.\n// Do not hand-edit; update source-assets/spatial-controller/screens/*.svg and regenerate.\nexport const controllerScreenBleed = ${perspectiveBleed}\nexport const controllerScreenZones = ${JSON.stringify(zones, null, 2)}\n`
fs.writeFileSync(outputFile, output)
console.log(`Generated ${zones.length} screen zones at ${path.relative(projectRoot, outputFile)}`)
